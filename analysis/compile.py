"""Compile all results into tables, figures and analysis/RESULTS.md.

    python -m analysis.compile                 # uses RESULTS_ROOT or the repository
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from analysis import plots, stats  # noqa: E402
from common import configs  # noqa: E402
from common.paths import REPO_ROOT, results_root  # noqa: E402
from common.report import completeness, merge_results  # noqa: E402

OUT = REPO_ROOT / "analysis"
TABLES, FIGURES = OUT / "tables", OUT / "figures"


def md_table(df, floatfmt=".4f", index=False):
    d = df.reset_index() if index else df
    cols = list(d.columns)

    def fmt(v):
        if isinstance(v, (float, np.floating)):
            return "" if v != v else format(v, floatfmt)
        return str(v)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(fmt(v) for v in row) + " |" for row in d.itertuples(index=False)]
    return "\n".join(lines)


def pm(mean, sd):
    return f"{mean:.4f} ± {sd:.4f}"


def _complete(comp, dataset, experiment, require_complete):
    """True when every config of this dataset/experiment has all its rows."""
    try:
        part = comp.loc[(dataset, experiment)]
    except KeyError:
        return False
    if experiment == "main" and len(part) < len(configs.CONFIGS):
        return False
    return bool(part["complete"].all()) if require_complete else True


def compile_results(root=None, include_smoke=False, require_complete=True):
    """Only complete experiments are analysed (a partial E2 or E3 would skew the
    averages); the completeness table lists what is still missing."""
    TABLES.mkdir(parents=True, exist_ok=True)
    FIGURES.mkdir(parents=True, exist_ok=True)
    df = merge_results(root or results_root(), include_smoke=include_smoke)
    if df.empty:
        print("No results to compile.")
        return None
    df.to_csv(TABLES / "all_results.csv", index=False)
    comp = completeness(df)
    comp.to_csv(TABLES / "completeness.csv")

    all_ds = sorted(set(df["dataset"]))
    datasets = [d for d in all_ds if _complete(comp, d, "main", require_complete)]
    e2_done = [d for d in datasets if _complete(comp, d, "e2", require_complete)]
    e3_done = "cicids2017" in all_ds and _complete(comp, "cicids2017", "e3", require_complete)
    pending = [d for d in all_ds if d not in datasets]
    e3_rows = df[df["experiment"] == "e3"] if e3_done else df.iloc[0:0]
    keep = ((df["experiment"] == "main") & df["dataset"].isin(datasets)) | \
           ((df["experiment"] == "e2") & df["dataset"].isin(e2_done))
    df = df[keep]
    main = stats.main_only(df)
    md = ["# Results: factorial ablation of imbalance corrections", ""]
    md.append(f"Datasets compiled: {', '.join(plots.TITLES.get(d, d) for d in datasets)}. "
              f"{len(df) + len(e3_rows):,} result rows. Generated by `analysis/compile.py`; every "
              "number below is recomputed from the CSVs in `*/*/results/`.")
    if pending:
        md.append(f"Not yet included (main configs incomplete): {', '.join(pending)}.")
    missing_e2 = [d for d in datasets if d not in e2_done]
    if missing_e2:
        md.append(f"E2 not yet complete (left out of section 7): {', '.join(missing_e2)}.")
    if "cicids2017" in all_ds and not e3_done:
        md.append("E3 (CIC-IDS2017 imbalance sweep) not yet complete (section 9 left out).")
    md.append("")
    md += ["## 0. Completeness", "", md_table(comp, index=True), ""]

    # ---- main table -----------------------------------------------------------
    tab = stats.results_table(df)
    tab.to_csv(TABLES / "macro_f1_by_config.csv", index=False)
    wide = tab.assign(v=[pm(m, s) for m, s in zip(tab["mean"], tab["std"])]).pivot(
        index="config_id", columns="dataset", values="v").reindex(list(configs.CONFIGS))
    plots.main_bars(tab, FIGURES / "fig1_macro_f1_by_config.png")
    md += ["## 1. Macro-F1 by configuration",
           "Mean ± SD over the 10 outer folds, after averaging the 7 classifiers within each fold.",
           "", md_table(wide, index=True), "",
           "![Macro-F1 by config](figures/fig1_macro_f1_by_config.png)", ""]
    by_clf = stats.results_table(df, by_classifier=True)
    by_clf.to_csv(TABLES / "macro_f1_by_config_and_classifier.csv", index=False)
    plots.heatmap(by_clf, FIGURES / "fig2_heatmap_classifier_config.png")
    md += ["Per classifier (mean over folds):", "",
           "![Heatmap](figures/fig2_heatmap_classifier_config.png)", ""]
    for ds in datasets:
        w = by_clf[by_clf["dataset"] == ds].pivot(index="classifier", columns="config_id",
                                                   values="mean").reindex(columns=list(configs.CONFIGS))
        md += [f"**{plots.TITLES.get(ds, ds)}**", "", md_table(w.rename(columns=plots.SHORT), index=True), ""]

    # other metrics, averaged over classifiers
    other = main.groupby(["dataset", "config_id"])[
        ["mcc", "pr_auc", "roc_auc", "balanced_acc", "gmean", "precision_1", "recall_1"]].mean()
    other.round(4).to_csv(TABLES / "other_metrics_by_config.csv")
    md += ["## 2. Other metrics (mean over classifiers and folds)", "",
           md_table(other.round(4), index=True), ""]

    # ---- factorial effects ----------------------------------------------------
    eff = stats.factorial_effects(df)
    eff.to_csv(TABLES / "factorial_effects.csv", index=False)
    plots.effects_forest(eff, FIGURES / "fig3_factorial_effects.png")
    e_all = eff[eff["classifier"] == "ALL"].copy()
    e_all["CI"] = [f"[{a:.4f}, {b:.4f}]" for a, b in zip(e_all["ci_low"], e_all["ci_high"])]
    md += ["## 3. Factorial effects (reviewer R2)",
           "Yates effects of the 2x2x2 design on macro-F1: mean with the factor on minus mean with it "
           "off (interactions: difference of differences). 95% CI from 2,000 paired bootstrap "
           "resamples of the outer folds, averaged over the 7 classifiers. A = SMOTETomek, "
           "B = class weights (original ratio), C = threshold tuning.", "",
           md_table(e_all[["dataset", "term", "effect", "CI", "significant"]]), "",
           "![Effects](figures/fig3_factorial_effects.png)", ""]
    try:
        pooled, fit = stats.pooled_model(df)
        pooled.to_csv(TABLES / "pooled_model.csv", index=False)
        md += ["Pooled over datasets (OLS on fold-level scores, dataset and classifier fixed "
               "effects, standard errors clustered by outer fold; effect = 2 x coefficient):", "",
               md_table(pooled), ""]
    except Exception as e:  # e.g. only one dataset in smoke data
        md += [f"(Pooled model not estimated: {e})", ""]
    plots.interaction(main, FIGURES / "fig4_interaction_AB.png")
    md += ["![A x B interaction](figures/fig4_interaction_AB.png)", ""]

    # ---- pairwise tests ---------------------------------------------------------
    pw = stats.pairwise_tests(df)
    pw.to_csv(TABLES / "pairwise_tests.csv", index=False)
    show = pw.assign(CI=[f"[{a:.4f}, {b:.4f}]" for a, b in zip(pw["ci_low"], pw["ci_high"])])
    md += ["## 4. Key comparisons (reviewers R6, R7)",
           "Blocks = dataset x classifier. `median_diff` = second config minus first on macro-F1. "
           "Wilcoxon signed-rank over blocks with Holm correction; rank-biserial r in [-1, 1]; "
           "`blocks_sig_5x2cv` = blocks where Alpaydin's 5x2cv F-test gives p < 0.05, "
           "`of_which_better` = how many of those favour the second config.", "",
           "Note on c8: SMOTETomek balances the training data to exactly 1:1, and its Tomek-link "
           "step removes linked pairs from both classes, so the balance stays exact. Weights "
           "recomputed after resampling are therefore exactly 1 and c8 is identical to c1 "
           "(resampling alone). Recomputing only changes anything when resampling does not fully "
           "balance the data; E2 covers that case (SMOTETomek to 1:2 with `recalc`).", "",
           md_table(show[["comparison", "question", "blocks", "median_diff", "CI", "wins", "losses",
                          "p_holm", "rank_biserial", "blocks_sig_5x2cv", "of_which_better"]]), ""]

    # ---- ranking ------------------------------------------------------------------
    try:
        ranks, p, cd, n = stats.friedman_nemenyi(df)
        ranks.rename("avg_rank").to_csv(TABLES / "average_ranks.csv")
        plots.cd_diagram(ranks, cd, n, p, FIGURES / "fig5_ranking.png")
        md += ["## 5. Ranking of the 9 configurations",
               f"Friedman test over {n} blocks: p = {p:.3g}. Nemenyi critical difference = {cd:.2f} "
               "ranks: configs closer than this to each other are not significantly different.", "",
               md_table(ranks.rename("average rank (1 = best)").to_frame(), floatfmt=".2f", index=True),
               "", "![Ranking](figures/fig5_ranking.png)", ""]
    except Exception as e:
        md += [f"## 5. Ranking\n(not computed: {e})", ""]

    # ---- mechanism ------------------------------------------------------------------
    mech = stats.mechanism_summary(df)
    mech.to_csv(TABLES / "over_correction_by_config.csv")
    plots.over_correction(mech, FIGURES / "fig6_predicted_positive_ratio.png")
    md += ["## 6. Over-correction mechanism",
           "`rho_eff` = positive:negative loss mass the classifier sees (1 = balanced). "
           "`ppr_ratio` = predicted positive rate / true positive rate (1 = as many positives "
           "predicted as exist; above 1 = over-predicting the minority). Values are the median "
           "over the 7 classifiers of each classifier's mean over folds.", "",
           md_table(mech, floatfmt=".3f", index=True), "",
           "![PPR](figures/fig6_predicted_positive_ratio.png)", ""]

    e2 = df[df["experiment"] == "e2"]
    if len(e2):
        curves = stats.e2_curves(df)
        curves.to_csv(TABLES / "e2_curves.csv", index=False)
        plots.e2_curves(curves, FIGURES / "fig7_weight_sensitivity.png")
        mt = stats.mechanism_tests(df)
        mt.to_csv(TABLES / "e2_mechanism_slopes.csv", index=False)
        peak = stats.macro_f1_peak(df)
        peak.to_csv(TABLES / "e2_macro_f1_peak.csv", index=False)
        md += ["## 7. Weight sensitivity (E2, reviewer R3)",
               "Positive-class weight = IR^power, power in {0, 0.25, ..., 2}, with no resampling or "
               "SMOTETomek to 1:2 / 1:1, each with default and tuned threshold. x-axis: log2 rho_eff.",
               "", "![E2](figures/fig7_weight_sensitivity.png)", "",
               "Slopes against log2(rho_eff) for rho_eff >= 1 (per dataset x classifier). "
               "Over-correction predicts a negative precision slope and a positive PPR slope; "
               "threshold tuning (C = 1) should flatten both.", "",
               md_table(mt[["dataset", "classifier", "C", "points", "slope_precision_1",
                            "p_precision_1", "slope_ppr_ratio", "p_ppr_ratio",
                            "slope_macro_f1", "p_macro_f1"]]), "",
               "Where macro-F1 peaks along log2(rho_eff) (quadratic fit):", "",
               md_table(peak, floatfmt=".3f"), ""]
    meta = []
    for ds in datasets:
        p = REPO_ROOT / ds / "meta_features" / f"{ds}__meta_features.csv"
        if p.exists():
            meta.append(pd.read_csv(p))
    if meta:
        mf = pd.concat(meta, ignore_index=True)
        mf.to_csv(TABLES / "dataset_meta_features.csv", index=False)
        md += ["## 8. Dataset properties (Table 1)", "", md_table(mf), ""]

    if len(e3_rows):
        e3_rows.to_csv(TABLES / "e3_results.csv", index=False)
        t3 = stats.e3_table(e3_rows)
        t3.to_csv(TABLES / "e3_macro_f1_by_level.csv")
        eff3 = stats.e3_effects(e3_rows)
        eff3.to_csv(TABLES / "e3_effects_by_level.csv", index=False)
        plots.e3_effects(eff3, FIGURES / "fig8_e3_effects_vs_imbalance.png")
        show3 = eff3[eff3["term"].isin(["A", "B", "C", "AB"])].copy()
        show3["CI"] = [f"[{a:.4f}, {b:.4f}]" for a, b in zip(show3["ci_low"], show3["ci_high"])]
        show3 = show3.pivot(index="term", columns="minority_share", values="effect").reindex(
            ["A", "B", "C", "AB"]).sort_index(axis=1, ascending=False)
        t3.columns = [f"{c:.0%} Bot" for c in t3.columns]
        show3.columns = [f"{c:.0%} Bot" for c in show3.columns]
        md += ["## 9. Controlled imbalance sweep (E3, CIC-IDS2017 BENIGN vs Bot)",
               f"N = 10,000 flows at each minority share; levels are nested, so only the imbalance "
               f"changes. Classifiers: {', '.join(sorted(e3_rows['classifier'].unique()))}; "
               "10 search candidates per fold.", "",
               "Macro-F1 by config (mean over classifiers and folds):", "",
               md_table(t3, index=True), "",
               "Factorial effects on macro-F1 at each level (95% CIs in "
               "`tables/e3_effects_by_level.csv`):", "",
               md_table(show3, index=True), "",
               "![E3](figures/fig8_e3_effects_vs_imbalance.png)", ""]

    (OUT / "RESULTS.md").write_text("\n".join(md), encoding="utf-8")
    print("wrote", OUT / "RESULTS.md", "and",
          len(list(TABLES.glob("*.csv"))), "tables,", len(list(FIGURES.glob("*.png"))), "figures")
    return df


if __name__ == "__main__":
    smoke = "--smoke" in sys.argv
    compile_results(include_smoke=smoke, require_complete=not smoke)
